export type SafeErrorCode = keyof typeof SAFE_ERROR_REGISTRY;

export function isSafeErrorCode(value: unknown): value is SafeErrorCode {
  return typeof value === 'string' && Object.prototype.hasOwnProperty.call(SAFE_ERROR_REGISTRY, value);
}

export function getSafeErrorDefinition(code: SafeErrorCode): SafeErrorDefinition {
  return SAFE_ERROR_REGISTRY[code];
}
