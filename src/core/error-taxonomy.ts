export type ErrorDomain = typeof ERROR_DOMAINS[number];
export type ErrorProvider = typeof ERROR_PROVIDERS[number];
export type ErrorStage = typeof ERROR_STAGES[number];
export type ErrorClass = typeof ERROR_CLASSES[number];
export type Retryability = typeof RETRYABILITIES[number];
export type Visibility = typeof VISIBILITIES[number];
export type Ambiguity = typeof AMBIGUITIES[number];

export interface SafeErrorDefinition {
  domain: ErrorDomain;
  provider: ErrorProvider;
  stage: ErrorStage;
  class: ErrorClass;
  retryability: Retryability;
  visibility: Visibility;
  ambiguity: Ambiguity;
}

function definition(
  domain: ErrorDomain,
  provider: ErrorProvider,
  stage: ErrorStage,
  errorClass: ErrorClass,
  retryability: Retryability,
  visibility: Visibility = 'NON_VISIBLE',
  ambiguity: Ambiguity = 'NONE'
): SafeErrorDefinition {
  return { domain, provider, stage, class: errorClass, retryability, visibility, ambiguity };
}

